import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
const problems=[];
for(const width of [390,1280]){
 const ctx=await browser.newContext({viewport:{width,height:900}});
 await ctx.addInitScript(()=>localStorage.setItem('els-theme-v2','neutral-dark'));
 const page=await ctx.newPage();
 page.on('pageerror',e=>problems.push(width+' JS error: '+e.message));
 await page.goto('http://127.0.0.1:8765/c-programming/',{waitUntil:'networkidle'});
 const cards=page.locator('#available-chapters .path-card');
 if(await cards.count()!==4)problems.push(width+' expected four available chapter cards');
 const chapters=await cards.locator('.number').allTextContents();
 if(chapters.join('|')!=='15 / Chapter 15|16 / Chapter 16|17 / Chapter 17|18 / Chapter 18')problems.push(width+' order incorrect: '+chapters);
 if(await page.getByText('세 단원을 하나의 흐름으로').count())problems.push(width+' obsolete heading');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+3))problems.push(width+' home horizontal scroll');

 if(await page.locator('a[href*="quick-labs"]').count())problems.push(width+' unexpected Quick Labs link');
 const fullUnit=page.locator('#units a.unit-live');
 if(await fullUnit.count()!==4)problems.push(width+' expected 4 fully linked roadmap cards');
 if(await fullUnit.first().getAttribute('href')!=='./pointer/')problems.push(width+' roadmap card destination incorrect');
 if(await page.locator('#course-overview-details').evaluate(e=>e.open))problems.push(width+' overview should begin collapsed');
 await page.locator('#course-roadmap-link').click();
 if(!await page.locator('#course-overview-details').evaluate(e=>e.open))problems.push(width+' roadmap link did not open overview');
 if(await page.locator('#units .unit').count()!==18)problems.push(width+' expected 18 roadmap chapters');
 await page.goto('http://127.0.0.1:8765/c-programming/#roadmap',{waitUntil:'networkidle'});
 if(!await page.locator('#course-overview-details').evaluate(e=>e.open))problems.push(width+' direct #roadmap link did not open overview');

 await page.goto('http://127.0.0.1:8765/c-programming/dynamic-memory/',{waitUntil:'networkidle'});
 const heap=page.locator('.dm-heap');
 await heap.waitFor();
 if(await page.locator('.dm-nav-group').count()!==2)problems.push(width+' core / optional split missing');
 await heap.locator('[data-phase=used]').click();
 if(!(await heap.locator('#dm-detail').innerText()).includes('값 10'))problems.push(width+' selected cell value wrong');
 await heap.locator('[data-index="3"]').click();
 if(!(await heap.locator('#dm-detail').innerText()).includes('0x100C'))problems.push(width+' pointer address incorrect');
 await heap.locator('[data-phase=released]').click();
 if(!(await heap.locator('#dm-pointer-value').innerText()).includes('NULL'))problems.push(width+' free pointer state incorrect');
 await heap.locator('.dm-leak summary').click();
 await heap.locator('[data-leak=lost]').click();
 if(await heap.locator('.dm-leak-block.lost').count()!==1)problems.push(width+' leak not visible');
 await heap.locator('[data-leak=clean]').click();
 if(await heap.locator('.dm-leak-block.freed').count()!==2)problems.push(width+' cleanup state wrong');
 await heap.locator('#dm-play').click();
 await page.waitForTimeout(1600);
 if(await heap.getAttribute('data-phase')!=='used')problems.push(width+' playback did not progress');
 await page.waitForTimeout(1500);
 if(await heap.getAttribute('data-phase')!=='released')problems.push(width+' playback did not release');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+3))problems.push(width+' lab horizontal scroll');
 await page.screenshot({path:'qa-dynamic-memory-'+width+'.png',fullPage:true});
 await page.goto('http://127.0.0.1:8765/c-programming/dynamic-memory/practice/',{waitUntil:'networkidle'});
 const help=page.locator('.cp-coach');
 if(!await help.isVisible())problems.push(width+' P1 coaching missing');
 const hint=help.locator('.cp-coach-reveal').first();
 await hint.click();
 if(!await help.locator('.cp-coach-help').first().isVisible())problems.push(width+' hint not revealed');
 await page.locator('.cp-nav-item').nth(1).click();
 if(!await help.isVisible())problems.push(width+' P2 coaching missing');
 await page.locator('.cp-nav-item').nth(2).click();
 if(!await help.isVisible())problems.push(width+' P3 coaching missing');
 await page.locator('.cp-nav-item').nth(3).click();
 if(await help.isVisible())problems.push(width+' P4 coaching should be hidden');
 await page.screenshot({path:'qa-c-practice-'+width+'.png',fullPage:true});
 await ctx.close();
}
await browser.close();
if(problems.length){console.error(problems.join('\n'));process.exit(1)}
console.log('PASS: chronological cards, 181 heap state, pointer addresses, leak cleanup, playback and P1-P3 hints at 390/1280px.');
